package ru.rim.dd.core.ble

import ru.rim.dd.core.log.AppLog

/**
 * Восстановление «битого» сопряжения: система считает прибор сопряжённым, но ключи не подходят
 * (прибор забыл их, или связь осталась от старой установки). Запрос PIN тогда не появляется вовсе —
 * Android не пересопрягает уже сопряжённое устройство. Один раз за подключение связь удаляется,
 * и сопряжение проходит заново. Если удалить не удалось — пользователю остаётся подсказка.
 *
 * Класс хранит только состояние «уже пробовали» и текст подсказки; что именно значит «удалить
 * связь» и «разорвать соединение», решает вызывающий код (лямбды), поэтому Android здесь не нужен.
 */
internal class BondRecovery {

    private var handled = false

    /** Подсказка пользователю, если связь удалить не удалось; null — подсказки нет. */
    var hint: String? = null
        private set

    /** Новое подключение: можно снова пробовать восстановление. */
    fun reset() {
        handled = false
        hint = null
    }

    /**
     * Шифрованный обмен не состоялся у сопряжённого прибора. Срабатывает не чаще раза за подключение.
     *
     * @param removeBond удалить сопряжение; true — удалось.
     * @param dropConnection разорвать GATT, чтобы следующая попытка прошла с нуля и система показала запрос PIN.
     * @return true — восстановление запущено сейчас; false — уже пробовали в этом подключении.
     */
    fun onEncryptionFailure(removeBond: () -> Boolean, dropConnection: () -> Unit): Boolean {
        if (handled) return false
        handled = true
        AppLog.w("MeterBleClient", "Прибор сопряжён, но шифрованный обмен не удался — удаляем старую связь и сопрягаем заново")
        if (!removeBond()) hint = STALE_PAIRING_HINT
        dropConnection()
        return true
    }

    companion object {
        const val STALE_PAIRING_HINT = "Не удалось пересопрячься с прибором. Откройте настройки Bluetooth телефона, " +
                "удалите прибор из списка сопряжённых устройств и подключитесь заново"
    }
}

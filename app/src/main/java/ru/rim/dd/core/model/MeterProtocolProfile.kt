package ru.rim.dd.core.model

/**
 * [Android-патч] Диалект DLMS/COSEM, на котором говорит конкретный прибор.
 *
 * ЗАЧЕМ ПОЯВИЛОСЬ: до сих пор всё приложение было построено вокруг одного способа общения —
 * того, что использует пульт РиМ 040.40. Когда в работу пошёл счётчик AKROS (тоже прибор РиМ),
 * выяснилось, что по BLE он подключается, а данные не читаются: разбор эталонного лога обмена
 * (с проверкой границ полей по HCS/FCS) показал, что у него ДРУГАЯ адресация, другой порядок
 * установления сеанса и обязательная DLMS-ассоциация с паролем.
 *
 * Различия сведены сюда, в один перечислимый профиль, а не размазаны условиями по коду: так
 * видно ровно, чем приборы отличаются, и добавление третьего прибора не превращается в охоту за
 * «if» по всему репозиторию.
 */
enum class MeterProtocolProfile {

    /**
     * Прибор РиМ через «плоскую» (однобайтовую) HDLC-адресацию — dest 0x03 (сервер 1),
     * src 0x43 (клиент 33), invoke-id 0x81.
     *
     * Особенности, найденные на реальных приборах и подтверждённые логом обмена пульта:
     * SNRM отправляется «на всякий случай», но ответа (UA) прибор НЕ присылает — ждать его
     * нельзя, это стоило 3 секунд на каждое подключение; DLMS-ассоциация (AARQ) не нужна и
     * ВРЕДНА — на AARQ прибор переставал отвечать на всё до конца BLE-сессии; все данные
     * читаются одним запросом буфера индикации 0.0.21.0.2.255 (класс 7), обычно 7+ сегментами.
     */
    RIM_FLAT,

    /**
     * Счётчик AKROS — стандартная адресация DLMS/COSEM и полноценный сеанс.
     *
     * Всё ниже вычитано из эталонного лога обмена штатной утилиты с прибором:
     *
     *  - адреса: клиент 32 (байт 0x41), сервер логический 1 / физический 16 (байты 0x02 0x21),
     *    то есть двухбайтовый адрес сервера вместо однобайтового у РиМ;
     *  - SNRM отправляется С согласованием параметров и прибор ОТВЕЧАЕТ UA (в отличие от РиМ),
     *    в ответе он сообщает max-info 128/128 и размер окна 1;
     *  - затем ОБЯЗАТЕЛЬНА ассоциация AARQ/AARE с низким уровнем безопасности (LLS, механизм
     *    2.16.756.5.8.2.1) и паролем — без неё запросы данных смысла не имеют;
     *  - invoke-id-and-priority в запросах — 0x41 (подтверждаемый сервис, обычный приоритет),
     *    причём утилита использует один и тот же invoke-id для всех запросов, то есть, в
     *    отличие от РиМ, прибор не считает повтор invoke-id обращением к старой транзакции.
     */
    AKROS_STANDARD;

    companion object {

        /**
         * Определяет диалект по имени устройства в эфире. Имя — самый ранний доступный признак:
         * оно известно ещё до подключения (из сканирования) и не требует «пробовать и смотреть,
         * что ответит», то есть не тратит время на заведомо неподходящий сеанс.
         *
         * Всё, что не опознано как AKROS, считается прибором РиМ — это сохраняет ровно прежнее
         * поведение для всех уже работающих приборов: новый профиль включается только там, где
         * он точно нужен.
         */
        fun forDeviceName(name: String?): MeterProtocolProfile =
            if (name?.contains(AKROS_NAME_MARKER, ignoreCase = true) == true) AKROS_STANDARD else RIM_FLAT

        /**
         * По этой подстроке узнаём AKROS. Проверяется именно «содержит», а не «начинается с»:
         * в эфире прибор рекламируется как «AKROS-07200090», а своё логическое имя (объект
         * 0.0.42.0.0.255) сообщает как «RIMAKROS07200090» — маркер один и тот же, и он же
         * сработает, если имя когда-нибудь получит приставку производителя.
         */
        const val AKROS_NAME_MARKER = "AKROS"
    }
}
